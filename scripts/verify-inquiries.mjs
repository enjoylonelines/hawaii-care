import assert from 'node:assert/strict';
import {loadEnv} from 'vite';
const env=loadEnv('development',process.cwd(),'VITE_');
const endpoint=env.VITE_INQUIRY_ENDPOINT;
const headers={'Content-Type':'application/json',Origin:'http://localhost:4178',apikey:env.VITE_SUPABASE_PUBLISHABLE_KEY,Authorization:'Bearer '+env.VITE_SUPABASE_ANON_KEY};
const payload={kind:'care',name:'INTEGRATION_TEST',phone:'01000000000',area:'TEST_DELETE',condition:'잘 모르겠어요',consent:true,website:''};
let r=await fetch(endpoint,{method:'OPTIONS',headers});assert.equal(r.status,204);
r=await fetch(endpoint,{method:'POST',headers,body:JSON.stringify({...payload,consent:false})});assert.equal(r.status,400);
r=await fetch(endpoint,{method:'POST',headers,body:JSON.stringify(payload)});const data=await r.json();assert.equal(r.status,201,JSON.stringify(data));assert.equal(data.ok,true);
r=await fetch(endpoint,{method:'POST',headers:{...headers,Origin:'https://untrusted.example'},body:JSON.stringify(payload)});assert.equal(r.status,403);
const base=new URL(endpoint).origin;
r=await fetch(base+'/rest/v1/inquiries?select=id',{headers:{apikey:env.VITE_SUPABASE_PUBLISHABLE_KEY,Authorization:'Bearer '+env.VITE_SUPABASE_ANON_KEY}});assert([401,403].includes(r.status));
console.log('PASS: CORS, validation, real insertion, origin rejection, anonymous read blocked. Remove INTEGRATION_TEST record after verification.');
